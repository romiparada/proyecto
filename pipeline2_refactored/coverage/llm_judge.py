"""Módulo de evaluación por LLM (LLM-as-a-Judge) para la cobertura funcional."""

import json
from typing import Dict, List, Any
from ..refinement.refinement_module import call_llm


def evaluate_coverage_with_llm(
    coverage_data: Dict[str, Any],
    api_key: str,
    model: str,
    batch_size: int = 10
) -> Dict[str, Any]:
    """
    Evalúa la cobertura de TODAS las funcionalidades utilizando un LLM.
    Actúa como un Retrieve-and-Judge, donde SBERT provee el Top-K y el LLM decide.
    """
    results = coverage_data.get("results", [])
    if not results:
        return coverage_data

    # Respaldar el status original de SBERT
    for res in results:
        res["sbert_status"] = res.get("coverage_status")

    total_results = len(results)
    
    # Procesar en lotes (batches) para no exceder tokens o perder formato JSON
    for i in range(0, total_results, batch_size):
        batch = results[i:i + batch_size]
        _process_batch(batch, api_key, model)

    # Recalcular el summary
    covered_llm = sum(1 for r in results if r.get("coverage_status") == "covered_by_llm")
    not_covered_llm = sum(1 for r in results if r.get("coverage_status") == "not_covered_by_llm")
    
    coverage_data["summary"] = {
        "total_functionalities": total_results,
        "covered_by_llm": covered_llm,
        "not_covered_by_llm": not_covered_llm,
        "coverage_percentage": (covered_llm / total_results) * 100 if total_results > 0 else 0.0
    }
    
    return coverage_data


def _process_batch(batch: List[Dict[str, Any]], api_key: str, model: str) -> None:
    """Construye un prompt para un lote de funcionalidades, llama al LLM y parsea la respuesta."""
    
    prompt_template = """You are an expert Requirements Engineer and Agile Analyst.
Your task is to determine if specific system functionalities are covered by generated User Stories.

For each functionality, you will be provided with the Top-3 most semantically related user stories generated by the system.
You must read the functionality and the 3 candidate stories. Then, use your logical reasoning to determine if the functionality is satisfied (either fully or partially) by ANY of these candidate stories, or by a combination of them.

EVALUATION CRITERIA:
- A functionality is COVERED if at least one candidate story explicitly or implicitly satisfies the goal described in the functionality. 
- IMPORTANT (Granularity Mismatch): Candidate stories are often written at a higher level of abstraction (Epic level). If a candidate story is broad (e.g., "manage appointments") and logically encompasses the specific functionality (e.g., "cancel an appointment"), you MUST consider it COVERED. Do not penalize a story for lacking highly specific details as long as the broader goal contains the functionality.
- A functionality is NOT COVERED if none of the candidate stories describe the goal, or if they describe a completely different context/actor that does not satisfy the requirement.

FUNCTIONALITIES TO EVALUATE:

{items}

---
TASK:
Analyze each functionality and return a JSON object EXACTLY following this structure.
Do not include any markdown blocks like ```json or any other text outside the JSON object.

{{
  "evaluations": [
    {{
      "functionality_id": "<must perfectly match the ID provided above>",
      "is_covered": true or false,
      "reasoning": "A brief 1-2 sentence explanation of your decision"
    }}
  ]
}}
"""

    items_text = ""
    for idx, item in enumerate(batch):
        func_id = f"FUNC_{idx}"
        item["_temp_id"] = func_id # Temporal ID for matching the response
        
        items_text += f"ID: {func_id}\n"
        items_text += f"Functionality: [{item['category']}] {item['functionality']}\n"
        items_text += "Candidate Stories:\n"
        
        top_matches = item.get("top_matches", [])
        if not top_matches:
            items_text += "- None\n"
        else:
            for j, match in enumerate(top_matches):
                items_text += f"  {j+1}. {match['story_text']}\n"
        items_text += "\n"

    prompt = prompt_template.format(items=items_text)

    try:
        response_text = call_llm(prompt, api_key, model)

        # Limpiar markdown
        if response_text.startswith("```json"):
            response_text = response_text[7:]
        if response_text.endswith("```"):
            response_text = response_text[:-3]
            
        json_output = json.loads(response_text.strip())
        evaluations = json_output.get("evaluations", [])
        
        # Mapear de vuelta al lote
        eval_map = {e["functionality_id"]: e for e in evaluations if "functionality_id" in e}
        
        for item in batch:
            temp_id = item.get("_temp_id")
            evaluation = eval_map.get(temp_id)
            
            if evaluation:
                is_covered = evaluation.get("is_covered", False)
                reasoning = evaluation.get("reasoning", "No reasoning provided by LLM.")
                item["coverage_status"] = "covered_by_llm" if is_covered else "not_covered_by_llm"
                item["llm_reasoning"] = reasoning
            else:
                item["coverage_status"] = "llm_evaluation_failed"
                item["llm_reasoning"] = "LLM did not return an evaluation for this functionality."
            
            # Limpiar ID temporal
            if "_temp_id" in item:
                del item["_temp_id"]
                
    except Exception as e:
        # En caso de error de red o JSON, marcamos como fallido para que no se pierdan los datos
        for item in batch:
            item["coverage_status"] = "llm_evaluation_error"
            item["llm_reasoning"] = f"Error calling LLM: {str(e)}"
            if "_temp_id" in item:
                del item["_temp_id"]
